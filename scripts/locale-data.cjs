// Builds js/ruxget-locale-data.js from _locales/*/messages.json.
// The inherited tool pages (m3u8, mpd, json, downloader, preview, popup, options) translate synchronously while they load,
// so they read the Ruxget interface language (ruxgetUiLanguage) from this file instead of waiting for an async fetch.
//   node scripts/locale-data.cjs          rewrite js/ruxget-locale-data.js in the source tree
//   node scripts/locale-data.cjs --check  exit 1 when the file no longer matches _locales
// scripts/package.cjs regenerates it inside build/ and build-full/ from each edition's own _locales.
const fs = require('node:fs');
const path = require('node:path');
const FILE = 'js/ruxget-locale-data.js';

function render(localesDir) {
  const langs = fs.readdirSync(localesDir, {withFileTypes:true}).filter(d => d.isDirectory() && fs.existsSync(path.join(localesDir, d.name, 'messages.json'))).map(d => d.name).sort();
  const blocks = langs.map(lang => {
    const messages = JSON.parse(fs.readFileSync(path.join(localesDir, lang, 'messages.json'), 'utf8').replace(/^\uFEFF/, ''));
    const lines = Object.keys(messages).map(key => {
      const entry = {message: String(messages[key].message ?? '')};
      const ph = messages[key].placeholders;
      if (ph) { entry.placeholders = {}; for (const name of Object.keys(ph)) entry.placeholders[name] = {content: String(ph[name].content ?? '')}; }
      return JSON.stringify(key) + ':' + JSON.stringify(entry);
    });
    return JSON.stringify(lang) + ':{\n' + lines.join(',\n') + '\n}';
  });
  return '// Generated by scripts/locale-data.cjs from _locales/*/messages.json. Do not edit by hand.\n' +
    '// Loaded before js/polyfill.js so pages know the Ruxget interface language synchronously.\n' +
    'globalThis.RuxgetLocaleData={\n' + blocks.join(',\n') + '\n};\n';
}

// Writes <folder>/js/ruxget-locale-data.js from <folder>/_locales. Returns true when the file changed.
function write(folder) {
  const target = path.join(folder, FILE), text = render(path.join(folder, '_locales'));
  const before = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (before === text) return false;
  fs.writeFileSync(target, text);
  return true;
}

function inSync(folder) {
  const target = path.join(folder, FILE);
  return fs.existsSync(target) && fs.readFileSync(target, 'utf8') === render(path.join(folder, '_locales'));
}

module.exports = {FILE, render, write, inSync};

if (require.main === module) {
  const root = path.resolve(__dirname, '..');
  if (process.argv.includes('--check')) {
    if (!inSync(root)) { console.error(FILE + ' is out of date; run node scripts/locale-data.cjs'); process.exit(1); }
    console.log(FILE + ' matches _locales');
  } else {
    console.log(write(root) ? 'wrote ' + FILE : FILE + ' already up to date');
  }
}
